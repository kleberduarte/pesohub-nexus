export const LARGURA_GLIFO_CONDENSADO = 4;
export const ALTURA_GLIFO_CONDENSADO = 7;

/** Converte a arte ASCII em colunas de bits (bit 0 = linha do topo). */
function paraColunas(linhas: string[]): number[] {
  const colunas: number[] = [];
  for (let col = 0; col < LARGURA_GLIFO_CONDENSADO; col++) {
    let bits = 0;
    for (let lin = 0; lin < ALTURA_GLIFO_CONDENSADO; lin++) {
      if (linhas[lin]?.[col] === "#") bits |= 1 << lin;
    }
    colunas.push(bits);
  }
  return colunas;
}

export const FONTE_CONDENSADA: Record<string, number[]> = Object.fromEntries(
  Object.entries(DESENHOS).map(([ch, linhas]) => [ch, paraColunas(linhas)]),
);
